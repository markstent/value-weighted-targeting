def add_learner_macros(M, learners):
    kappas = learners['kappas']
    w = learners['welfare']
    i = kappas.index(DEFAULT_KAPPA)
    for combo in learner_combos(learners):
        lr_tn, vm = combo.split('|')
        lr, tn = lr_tn.split(' ')
        tn = tn.strip('()').capitalize()
        vtag = {'misspec': 'Misspec', 'wellspec': 'Wellspec', 'tau': 'TauOnly'}[vm]
        for k in (0.1, 0.3):
            ki = kappas.index(k)
            M.add(f'numLearnersWelfare{lr}{tn}{vtag}{kappa_tag(k)}', fmt_welfare(w[combo][ki]['mean']), f'mean welfare, {combo}, kappa={k}', f'learners.json:welfare/{combo}[{ki}]/mean')
    s_t = w['S (tuned)|misspec'][i]['mean'] - w['T (tuned)|misspec'][i]['mean']
    M.add('numLearnersSMinusTTunedKthirty', fmt_signed(s_t, fmt_welfare), 'welfare of S (tuned) minus T (tuned), misspecified V, kappa=0.30 (difference of means; no paired test is stored)', 'learners.json:welfare/S (tuned)|misspec, T (tuned)|misspec')
    for combo, tag in (('S (tuned)|misspec', 'STunedVsTDefault'), ('T (tuned)|misspec', 'TTunedVsTDefault')):
        t = next(t for t in learners['tests_vs_T_default'][key_str(DEFAULT_KAPPA)] if t['combo'] == combo)
        src = f'learners.json:tests_vs_T_default/0.3[{combo}]'
        M.add(f'numLearnersDiff{tag}Kthirty', fmt_signed(t['diff'], fmt_welfare), f'paired welfare difference, {combo} minus T (default)|misspec, kappa=0.30', src + '/diff')
        M.add(f'numLearnersHolmP{tag}Kthirty', fmt_p(t['p_holm']), f'Holm p, {combo} vs T (default)|misspec, kappa=0.30', src + '/p_holm')
        M.add(f'numLearnersD{tag}Kthirty', fmt_d(t['cohens_d']), f"Cohen's d, {combo} vs T (default)|misspec, kappa=0.30", src + '/cohens_d')
    split = learners['regret_split_kappa_0.30']
    for combo, tag in (('T (default)|misspec', 'TDefaultMisspec'), ('T (tuned)|misspec', 'TTunedMisspec'),
                       ('T (default)|wellspec', 'TDefaultWellspec')):
        sp = split[combo]
        src = f'learners.json:regret_split_kappa_0.30/{combo}'
        M.add(f'numLearnersShapleyCateShare{tag}', fmt_pct(sp['shapley_tau_share_of_mean']), f'Shapley CATE (tau) share of regret, {combo}, kappa=0.30', src + '/shapley_tau_share_of_mean')
        M.add(f'numLearnersShapleyValueShare{tag}', fmt_pct(sp['shapley_v_share_of_mean']), f'Shapley value-model (V) share of regret, {combo}, kappa=0.30', src + '/shapley_v_share_of_mean')
    sp = split['T (default)|misspec']['shapley_tau_share_per_rep']
    M.add('numLearnersShapleyCateShareCiLo', fmt_pct(sp['ci95'][0]), 'lower 95% CI of the per-replication Shapley CATE share, T (default)|misspec', 'learners.json:regret_split_kappa_0.30/T (default)|misspec/shapley_tau_share_per_rep/ci95')
    M.add('numLearnersShapleyCateShareCiHi', fmt_pct(sp['ci95'][1]), 'upper 95% CI of the per-replication Shapley CATE share, T (default)|misspec', 'learners.json:regret_split_kappa_0.30/T (default)|misspec/shapley_tau_share_per_rep/ci95')


