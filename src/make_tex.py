def strat_stats(main, name):
    """(welfare_mean, welfare_sd, risk_mean) for a strategy; unrounded oracle values where kept."""
    om = main["oracle_main"]["strategies"]
    if name in om:
        s = om[name]
        return s["welfare_mean"], s["welfare_sd"], s["risk_mean"]
    s = main["main_results"][name]
    return s["welfare_mean"], s["welfare_sd"], s["risk_mean"]


def strat_source(main, name):
    return (
        "main.json:oracle_main/strategies/" if name in main["oracle_main"]["strategies"] else "main.json:main_results/"
    ) + name


def budget_welfare(main, name, kappa):
    ob = main["oracle_budget"]["strategies"]
    if name in ob:
        return ob[name][key_str(kappa)]["welfare_mean"]
    return main["budget_sensitivity"][key_str(kappa)][name]["welfare_mean"]


def harm_cell(harm, c, sigma, kappa, rule, dgp="main"):
    for cell in harm["cells"]:
        if (
            cell["dgp"] == dgp
            and cell["c_harm"] == c
            and cell["sigma_h"] == sigma
            and cell["kappa"] == kappa
            and cell["rule"] == rule
        ):
            return cell
    raise KeyError(f"harm cell dgp={dgp} c={c} sigma={sigma} kappa={kappa} rule={rule!r}")


def kappa_star_text(ks, grid, which):
    """Point estimate or censored CI endpoint as text; '<0.050' / '>0.500' when censored."""
    lo, hi = min(grid), max(grid)
    if which == "point":
        if ks["point"] is not None:
            return fmt_kappa(ks["point"])
        outcome = ks["point_outcome"]
        if outcome == "below_grid":
            return "<" + fmt_kappa(lo)
        if outcome == "above_grid":
            return ">" + fmt_kappa(hi)
        raise ValueError(f"unknown kappa* point_outcome {outcome!r}")
    idx = {"lo": 0, "hi": 1}[which]
    label = ks["ci95_labels"][idx]
    if label == "<min":
        return "<" + fmt_kappa(lo)
    if label == ">max":
        return ">" + fmt_kappa(hi)
    return fmt_kappa(ks["ci95"][idx])


