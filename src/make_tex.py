def build(data):
    """Map output file name -> content, from the five loaded JSONs."""
    main, harm, b2 = data['main'], data['harm_sweep'], data['budget_2x2']
    learners, rob = data['learners'], data['robustness']
    M = Macros()
    add_main_macros(M, main)
    add_harm_macros(M, harm)
    add_kappa_star_macros(M, b2)
    add_learner_macros(M, learners)
    add_robustness_macros(M, rob)
    return {
        'numbers.tex': M.render(),
        'tab_main.tex': table_main(main),
        'tab_budget.tex': table_budget(main),
        'tab_kappa_star.tex': table_kappa_star(b2),
        'tab_harm.tex': table_harm(harm),
        'tab_learners.tex': table_learners(learners),
        'tab_robustness.tex': table_robustness(rob),
        'tab_calibration.tex': table_calibration(rob),
    }


def generated_names():
    return ['numbers.tex'] + [f'tab_{n}.tex' for n in TABLE_NAMES]


def load(outdir, smoke):
    suffix = '_smoke' if smoke else ''
    data = {}
    for base in INPUT_BASENAMES:
        with open(Path(outdir) / f'{base}{suffix}.json') as fh:
            data[base] = json.load(fh)
    return data


def write(outdir, gendir, smoke):
    files = build(load(outdir, smoke))
    gendir = Path(gendir)
    gendir.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, text in files.items():
        p = gendir / name
        p.write_text(text)
        paths.append(p)
    return paths


