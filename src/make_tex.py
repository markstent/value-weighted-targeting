def table_main(main):
    rows = []
    for nm in MAIN_ORDER:
        w, sd, r = strat_stats(main, nm)
        rows.append(row([STRATEGY_LABEL[nm], fmt_welfare(w), fmt_welfare(sd), fmt_harm(r)]))
    rows.append(r'\midrule')
    for nm in ORACLES_ORDER:
        w, sd, r = strat_stats(main, nm)
        rows.append(row([STRATEGY_LABEL[nm], fmt_welfare(w), fmt_welfare(sd), fmt_harm(r)]))
    return table(rows)


def table_budget(main):
    rows = []
    for k in BUDGET_KAPPAS:
        tests = main['budget_paired_tests'][key_str(k)]
        cells = [fmt_kappa(k)]
        cells += [fmt_welfare(budget_welfare(main, nm, k))
                  for nm in (*BUDGET_RULES, 'Oracle feasible (g=1)')]
        cells += [fmt_p(tests['cal_vs_cate_only']['p_holm']), fmt_p(tests['cal_vs_ltv']['p_holm'])]
        rows.append(row(cells))
    return table(rows)


def table_kappa_star(b2):
    grid = b2['kappa_grid']
    rows = []
    for key, cell in b2['cells'].items():
        tau_src, v_src = key.split('|')
        ks = cell['kappa_star']
        ci = f"[{kappa_star_text(ks, grid, 'lo')}, {kappa_star_text(ks, grid, 'hi')}]"
        rows.append(row([
            TAU_LABEL[tau_src], VMODEL_LABEL.get(v_src, v_src),
            fmt_count(ks['n_below_grid']), fmt_count(ks['n_crossing']), fmt_count(ks['n_above_grid']),
            kappa_star_text(ks, grid, 'point'), ci,
            fmt_pct(ks['frac_with_crossover']), fmt_count(ks['n_sign_changes'])]))
    return table(rows)


def table_harm(harm):
    meta = harm['_meta']
    rows = []
    for c in meta['c_harm']:
        for s in meta['sigma_h']:
            est = harm_cell(harm, c, s, DEFAULT_KAPPA, 'tauV')['exposure_minus_pop']
            cells = [fmt_fixed(c, 1), fmt_fixed(s, 1),
                     fmt_signed(est['mean'], fmt_harm) + ' ' + fmt_ci(*est['ci95'], fmt_harm)]
            for suffix in ('', ' (oracle tau,V)'):
                for rule in ('tauV', 'soft gate', 'hard cap'):
                    cells.append(fmt_welfare(
                        harm_cell(harm, c, s, DEFAULT_KAPPA, rule + suffix)['welfare']['mean']))
            rows.append(row(cells))
    return table(rows)


def learner_combos(learners):
    return [f'{lr} ({tn})|{vm}' for lr in LEARNERS for tn in ('tuned', 'default') for vm in VMODELS]


def table_learners(learners):
    kappas = learners['kappas']
    split = learners['regret_split_kappa_0.30']
    rows = []
    for combo in learner_combos(learners):
        lr_tn, vm = combo.split('|')
        cells = [lr_tn.replace(' (', ' ').rstrip(')'), VMODEL_LABEL[vm]]
        for k in (0.1, 0.3):
            i = kappas.index(k)
            cells.append(fmt_welfare(learners['welfare'][combo][i]['mean']))
            test = next((t for t in learners['tests_vs_T_default'][key_str(k)]
                         if t['combo'] == combo), None)
            cells.append(fmt_p(test['p_holm']) if test else '--')
        cells.append(fmt_pct(split[combo]['shapley_tau_share_of_mean']) if combo in split else '--')
        rows.append(row(cells))
    return table(rows)


