    M.add(base + "CiHi", fmt(hi), f"upper 95% CI of {base}", f"{src}/{ci_key}")
    M.add(base + "HolmP", fmt_p(t["p_holm"]), f"Holm-adjusted p, {what}", f"{src}/p_holm")


