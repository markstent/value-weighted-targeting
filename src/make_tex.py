def learner_combos(learners):
    return [f"{lr} ({tn})|{vm}" for lr in LEARNERS for tn in ("tuned", "default") for vm in VMODELS]


def find_test(rows, combo, baseline):
    """The test row for combo against exactly this baseline (None if absent)."""
    hits = [t for t in rows if t["combo"] == combo and t["baseline"] == baseline]
    if len(hits) > 1:
        raise ValueError(f"ambiguous test rows for {combo} vs {baseline}")
    return hits[0] if hits else None


def default_baseline(combo):
    """Baseline of a tests_vs_T_default row: T (default) with the same value model; E2E is
    compared with T (default)|misspec."""
    return f"T (default)|{combo.split('|')[1]}" if "|" in combo else "T (default)|misspec"


def shapley_cell(split, combo):
    """Per-replication mean Shapley CATE share with its CI ('--' when not available)."""
    sp = split.get(combo, {}).get("shapley_tau_share_per_rep")
    if not sp:
        return "--"
    return fmt_pct(sp["mean"]) + " " + fmt_ci(*sp["ci95"], fmt_pct)


def table_learners(learners):
    kappas = learners["kappas"]
    split = learners["regret_split_kappa_0.30"]
    rows = []
    for combo in learner_combos(learners):
        lr_tn, vm = combo.split("|")
        cells = [lr_tn.replace(" (", " ").rstrip(")"), VMODEL_LABEL[vm]]
        for k in (0.1, 0.3):
            i = kappas.index(k)
            cells.append(fmt_welfare(learners["welfare"][combo][i]["mean"]))
            test = find_test(learners["tests_vs_T_default"][key_str(k)], combo, default_baseline(combo))
            cells.append(fmt_p(test["p_holm"]) if test else "--")
        cells.append(shapley_cell(split, combo))
        rows.append(row(cells))
    return table(rows)


