"""Generate LaTeX number macros and table bodies from the result JSONs.

Usage:  python src/make_tex.py [--smoke]

Reads outputs/{main,harm_sweep,budget_2x2,learners,robustness}.json (the *_smoke.json
variants with --smoke) and writes, to docs/generated/ (docs/generated_smoke/ with --smoke,
so a smoke run never overwrites the tracked files):

  numbers.tex      one \\newcommand{\\num<Study><Quantity><Variant>}{...} per reported number,
                   preceded by a comment block documenting every macro (meaning, source path)
  tab_<name>.tex   table bodies only (rows, no table environment) for the manuscript to \\input

Every number is formatted here, in Python, by the shared formatters below; the manuscript
never hand-types or hand-computes a reported value.  Output is deterministic: the same
JSONs give byte-identical files.
"""

