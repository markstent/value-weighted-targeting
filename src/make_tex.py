def frontier_label(name):
    for a, b in FRONTIER_LABEL:
        name = name.replace(a, b)
    return name


def table_frontier(main):
    """Regulation configurations (welfare, risk exposure) and the inverted-g misspecification."""
    rows = [
        row([frontier_label(f["config"]), fmt_welfare(f["welfare_mean"]), fmt_harm(f["risk_mean"])])
        for f in main["frontier"]
    ]
    inv = main["misspecification"]["inverted_g"]
    rows.append(r"\midrule")
    rows.append(row([r"Inverted $g$", fmt_welfare(inv["welfare_mean"]), fmt_harm(inv["risk_mean"])]))
    return table(rows)


def calibration_rows(rob):
    cal = rob["aipw_calibration"]["cells"]["main"]
    out = []
    for tuning, suffix in (("default", ""), ("tuned", " (tuned)")):
        for method, wkey, skey in (
            ("AIPW", "Calibrated (aipw)", "aipw"),
            ("Plug-in", "Calibrated (plug-in)", "plugin"),
        ):
            comp = cal["comparisons"][f"{wkey + suffix} vs Identity (g=1){suffix}"]
            out.append(
                {
                    "tuning": tuning,
                    "method": method,
                    "sel": cal["selection"][tuning][skey],
                    "comp": comp,
                    "regret": cal["regret_vs_feasible"][wkey + suffix],
                    "degenerate": bool(comp.get("degenerate")),
                }
            )
    return out


def table_calibration(rob):
    """Identity-selection rate, calibrated-minus-identity paired test, and regret vs the
    feasible oracle.  Degenerate plug-in rows (identity by construction) are marked."""
    rows = [
        r"% Degenerate rows: the plug-in objective selects identity by construction "
        r"(difference exactly 0), so they have no Holm p-value."
    ]
    for r in calibration_rows(rob):
        sel, c = r["sel"], r["comp"]
        method = r["method"] + (r" (degenerate$^{\dagger}$)" if r["degenerate"] else "")
        rows.append(
            row(
                [
                    method,
                    r["tuning"],
                    fmt_pct(sel["identity_rate"]),
                    f"{sel['identity_selected']}/{sel['n_runs']}",
                    fmt_signed(c["mean_diff"], fmt_welfare) + " " + fmt_ci(*c["ci_95"], fmt_welfare),
                    "--" if r["degenerate"] else fmt_p(c["p_holm"]),
                    fmt_welfare(r["regret"]["mean"]) + " " + fmt_ci(*r["regret"]["ci95"], fmt_welfare),
                ]
            )
        )
    return table(rows)


