def harm_test(harm, c, sigma, kappa, comparison, components, dgp="main"):
    hits = [
        t
        for t in harm["paired_tests"]
        if (t["dgp"], t["c_harm"], t["sigma_h"], t["kappa"], t["comparison"], t["components"])
        == (dgp, c, sigma, kappa, comparison, components)
    ]
    if len(hits) != 1:
        raise KeyError(f"harm paired test dgp={dgp} c={c} sigma={sigma} kappa={kappa} {comparison} {components}")
    return hits[0]


