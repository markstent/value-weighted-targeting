def robustness_comparison(rob, section, cell, comp_key):
    block = rob[section]
    comps = block['comparisons'] if cell is None else block['cells'][cell]['comparisons']
    if comp_key is None:
        comp_key = next(iter(comps))
    return comp_key, comps[comp_key], block['holm_family_size']


def table_robustness(rob):
    rows = []
    for section, cell, label, comp_key in ROBUSTNESS_ROWS:
        key, c, fam = robustness_comparison(rob, section, cell, comp_key)
        rows.append(row([label, key.replace(' x ', r' $\times$ '),
                         fmt_signed(c['mean_diff'], fmt_welfare)
                         if section != 'obs_diagnostic' else fmt_signed(c['mean_diff'], lambda v: fmt_fixed(v, 1)),
                         fmt_d(c['cohens_d']), fmt_p(c['p_holm']), str(fam)]))
    return table(rows)


def calibration_rows(rob):
    cal = rob['aipw_calibration']['cells']['main']
    feasible = cal['welfare']['Oracle feasible']['mean']
    out = []
    for tuning, suffix in (('default', ''), ('tuned', ' (tuned)')):
        for method, wkey, skey in (('AIPW', 'Calibrated (aipw)', 'aipw'),
                                   ('Plug-in', 'Calibrated (plug-in)', 'plugin')):
            sel = cal['selection'][tuning][skey]
            w = cal['welfare'][wkey + suffix]
            out.append({'tuning': tuning, 'method': method, 'sel': sel, 'welfare': w,
                        'regret': feasible - w['mean']})
    return out


def table_calibration(rob):
    rows = []
    for r in calibration_rows(rob):
        sel = r['sel']
        rows.append(row([r['method'], r['tuning'], fmt_pct(sel['identity_rate']),
                         f"{sel['identity_selected']}/{sel['n_runs']}",
                         fmt_welfare(r['welfare']['mean']) + ' ' + fmt_ci(*r['welfare']['ci95'], fmt_welfare),
                         fmt_welfare(r['regret'])]))
    return table(rows)


