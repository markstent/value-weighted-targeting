def add_test(M, base, t, fmt, what, src, ci_key="ci_95", p_key="p_value", unit=""):
    """Emit a paired-comparison family: <base> (the difference), <base>CiLo, <base>CiHi,
    <base>D, <base>P (raw p) and <base>HolmP (omitted when the test has no Holm p, e.g. a
    degenerate by-construction comparison)."""
    diff = t.get("mean_diff", t.get("diff"))
    lo, hi = t[ci_key]
    M.add(base, fmt_signed(diff, fmt) + unit, f"paired difference, {what}", f"{src}/mean_diff")
    M.add(base + "CiLo", fmt(lo) + unit, f"lower 95% CI of {base}", f"{src}/{ci_key}")
    M.add(base + "CiHi", fmt(hi) + unit, f"upper 95% CI of {base}", f"{src}/{ci_key}")
    M.add(base + "D", fmt_d(t["cohens_d"]), f"Cohen's d, {what}", f"{src}/cohens_d")
    M.add(base + "P", fmt_p(t[p_key]), f"unadjusted p, {what}", f"{src}/{p_key}")
    if t.get("p_holm") is not None:
        M.add(base + "HolmP", fmt_p(t["p_holm"]), f"Holm-adjusted p, {what}", f"{src}/p_holm")


def add_ci_stat(M, base, stat, fmt, what, src):
    """A mean with its CI: <base>, <base>CiLo, <base>CiHi."""
    M.add(base, fmt(stat["mean"]), what, f"{src}/mean")
    M.add(base + "CiLo", fmt(stat["ci95"][0]), f"lower 95% CI of {base}", f"{src}/ci95")
    M.add(base + "CiHi", fmt(stat["ci95"][1]), f"upper 95% CI of {base}", f"{src}/ci95")


