def robustness_comparison(rob, section, cell, comp_key):
    block = rob[section]
    comps = block["comparisons"] if cell is None else block["cells"][cell]["comparisons"]
    return comp_key, comps[comp_key], block["holm_family_size"]


def robustness_unit(section):
    """(formatter, suffix) for the difference: welfare units, or percentage points for the
    obs_diagnostic CATE-share difference."""
    if section == "obs_diagnostic":
        return (lambda v: fmt_fixed(v, 1)), " pp"
    return fmt_welfare, ""


def fmt_p_or_dash(p):
    return "--" if p is None else fmt_p(p)


TUNED_KEY = "CATE x LTV (tuned) vs CATE Only (tuned)"


def tuned_comparison(rob, section, cell, comp_key):
    """The tuned-learner arm of a headline CATE x LTV vs CATE only row, or None."""
    if comp_key != "CATE x LTV vs CATE Only":
        return None
    comps = rob[section]["cells"][cell]["comparisons"]
    return comps.get(TUNED_KEY)


def table_robustness(rob):
    """Columns: scenario, comparison, difference, 95% CI, d, Holm p, family size, then the
    tuned-learner arm of the same comparison (difference with CI, Holm p; '--' where the
    scenario has no tuned arm)."""
    rows = []
    for section, cell, label, comp_key in ROBUSTNESS_ROWS:
        key, c, fam = robustness_comparison(rob, section, cell, comp_key)
        fmt, unit = robustness_unit(section)
        tc = tuned_comparison(rob, section, cell, comp_key)
        tuned = (
            [
                fmt_signed(tc["mean_diff"], fmt_welfare) + " " + fmt_ci(*tc["ci_95"], fmt_welfare),
                fmt_p_or_dash(tc["p_holm"]),
            ]
            if tc
            else ["--", "--"]
        )
        rows.append(
            row(
                [
                    label,
                    key.replace(" x ", r" $\times$ "),
                    fmt_signed(c["mean_diff"], fmt) + unit,
                    fmt_ci(*c["ci_95"], fmt) + unit,
                    fmt_d(c["cohens_d"]),
                    fmt_p_or_dash(c["p_holm"]),
                    str(fam),
                    *tuned,
                ]
            )
        )
    return table(rows)


