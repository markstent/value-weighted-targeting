def add_main_macros(M, main):
    for nm, tag in STRATEGY_TAG.items():
        w, sd, r = strat_stats(main, nm)
        src = strat_source(main, nm)
        label = nm
        M.add(f'numMainWelfare{tag}Kthirty', fmt_welfare(w), f'mean welfare, {label}, kappa=0.30', f'{src}/welfare_mean')
        M.add(f'numMainWelfareSd{tag}Kthirty', fmt_welfare(sd), f'SD of welfare, {label}, kappa=0.30', f'{src}/welfare_sd')
        M.add(f'numMainRisk{tag}Kthirty', fmt_harm(r), f'mean risk exposure, {label}, kappa=0.30', f'{src}/risk_mean')
    for k in BUDGET_KAPPAS:
        kt = kappa_tag(k)
        tests = main['budget_paired_tests'][key_str(k)]
        for nm in (*BUDGET_RULES, 'Oracle feasible (g=1)', 'Oracle hindsight (g=1)'):
            tag = STRATEGY_TAG[nm]
            src = ('main.json:oracle_budget/strategies/' if nm.startswith('Oracle')
                   else 'main.json:budget_sensitivity/' + key_str(k) + '/') + (
                nm + '/' + key_str(k) if nm.startswith('Oracle') else nm)
            M.add(f'numBudgetWelfare{tag}{kt}', fmt_welfare(budget_welfare(main, nm, k)),
                  f'mean welfare, {nm}, kappa={k}', src + '/welfare_mean')
        for tag, tkey, what in (('CalVsCateOnly', 'cal_vs_cate_only', 'Cal. (AIPW) vs CATE only'),
                                ('CalVsCateLtv', 'cal_vs_ltv', 'Cal. (AIPW) vs CATE x LTV')):
            t = tests[tkey]
            src = f'main.json:budget_paired_tests/{key_str(k)}/{tkey}'
            M.add(f'numBudgetDiff{tag}{kt}', fmt_signed(t['mean_diff'], fmt_welfare), f'paired welfare difference, {what}, kappa={k}', src + '/mean_diff')
            M.add(f'numBudgetHolmP{tag}{kt}', fmt_p(t['p_holm']), f'Holm-adjusted p, {what}, kappa={k}', src + '/p_holm')
            M.add(f'numBudgetD{tag}{kt}', fmt_d(t['cohens_d']), f"Cohen's d, {what}, kappa={k}", src + '/cohens_d')

    # hindsight vs feasible oracle, and efficiency of the best estimated rule
    hind, _, _ = strat_stats(main, 'Oracle hindsight (g=1)')
    feas, _, _ = strat_stats(main, 'Oracle feasible (g=1)')
    M.add('numMainOracleHindsightWelfare', fmt_welfare(hind), 'hindsight oracle (g=1) welfare, kappa=0.30', 'main.json:oracle_main/strategies/Oracle hindsight (g=1)/welfare_mean')
    M.add('numMainOracleFeasibleWelfare', fmt_welfare(feas), 'feasible oracle (g=1) welfare, kappa=0.30', 'main.json:oracle_main/strategies/Oracle feasible (g=1)/welfare_mean')
    M.add('numMainOracleFeasibleShareOfHindsight', fmt_pct(feas / hind), 'feasible oracle welfare as a share of hindsight oracle welfare', 'computed: feasible / hindsight')
    M.add('numMainOracleHindsightFeasibleGap', fmt_welfare(hind - feas), 'hindsight minus feasible oracle welfare', 'computed: hindsight - feasible')
    best = max(ESTIMATED, key=lambda n: strat_stats(main, n)[0])
    best_w = strat_stats(main, best)[0]
    M.add('numMainBestEstimatedRule', STRATEGY_LABEL[best], 'name of the estimated rule with the highest mean welfare at kappa=0.30', 'main.json:main_results (argmax over estimated rules)')
    M.add('numMainBestEstimatedWelfare', fmt_welfare(best_w), 'mean welfare of the best estimated rule at kappa=0.30', strat_source(main, best) + '/welfare_mean')
    M.add('numMainBestEstimatedOracleFeasibleEfficiency', fmt_pct(best_w / feas), 'welfare of the best estimated rule as a share of the feasible oracle (g=1)', 'computed: best estimated / feasible oracle')
    M.add('numMainRandomOracleFeasibleEfficiency', fmt_pct(strat_stats(main, 'Random')[0] / feas), 'random targeting welfare as a share of the feasible oracle (g=1)', 'computed: random / feasible oracle')


