# Precision per quantity type
WELFARE_DP, HARM_DP, KAPPA_DP, P_DP, D_DP, PCT_DP = 0, 3, 3, 3, 2, 1


# ---------------------------------------------------------------- formatters

def fmt_fixed(x, dp):
    """Fixed-point with dp decimals; negative zero prints as zero."""
    s = f'{float(x):.{dp}f}'
    return s[1:] if s.startswith('-') and float(s) == 0 else s


def fmt_thousands(s):
    """Insert the TeX-safe thousands separator {,} into the integer part of a number string."""
    sign = '-' if s.startswith('-') else ''
    body = s.lstrip('-')
    ipart, dot, frac = body.partition('.')
    groups = []
    while len(ipart) > 3:
        groups.insert(0, ipart[-3:])
        ipart = ipart[:-3]
    groups.insert(0, ipart)
    return sign + '{,}'.join(groups) + dot + frac


def fmt_welfare(x):
    return fmt_thousands(fmt_fixed(x, WELFARE_DP))


def fmt_harm(x):
    return fmt_fixed(x, HARM_DP)


def fmt_kappa(x):
    return fmt_fixed(x, KAPPA_DP)


def fmt_d(x):
    return fmt_fixed(x, D_DP)


def fmt_p(p):
    """p-value to 3 dp; anything that rounds below 0.001 prints as <0.001."""
    p = float(p)
    return '<0.001' if p < 0.0005 else fmt_fixed(p, P_DP)


def fmt_pct(frac):
    """Fraction to a 1-dp percentage, TeX-safe ('12.3\\%')."""
    return fmt_thousands(fmt_fixed(100.0 * float(frac), PCT_DP)) + r'\%'


def fmt_ci(lo, hi, fmt):
    return f'[{fmt(lo)}, {fmt(hi)}]'


def fmt_count(n):
    return fmt_thousands(str(int(n)))


def fmt_signed(x, fmt):
    """Explicit plus sign for positive values (differences)."""
    s = fmt(x)
    return s if s.startswith('-') or s.startswith('<') else '+' + s


def tex(s):
    """Make a formatted string safe in text and math mode: real minus signs, math-mode < and >."""
    s = re.sub(r'(?<![\w\\])-(?=[\d{])', r'\\ensuremath{-}', s)
    s = re.sub(r'([<>])', r'\\ensuremath{\1}', s)
    return s


# ---------------------------------------------------------------- macro naming

_ONES = ('zero one two three four five six seven eight nine ten eleven twelve thirteen '
         'fourteen fifteen sixteen seventeen eighteen nineteen').split()
_TENS = 'zero ten twenty thirty forty fifty sixty seventy eighty ninety'.split()
_DIGITS = {'0': 'Zero', '1': 'One', '2': 'Two', '3': 'Three', '4': 'Four', '5': 'Five',
           '6': 'Six', '7': 'Seven', '8': 'Eight', '9': 'Nine', '.': 'Point', '-': 'Minus'}


def spell_digits(text):
    """'0.075' -> 'ZeroPointZeroSevenFive': digits spelled out, letters only."""
    return ''.join(_DIGITS[c] for c in str(text))


def words_under_100(n):
    if n < 20:
        return _ONES[n]
    tens, ones = divmod(n, 10)
    return _TENS[tens] + (_ONES[ones] if ones else '')


def kappa_tag(kappa):
    """0.10 -> 'Kten', 0.30 -> 'Kthirty', 0.05 -> 'Kfive'; non-percent grids spell digits."""
    pct = round(float(kappa) * 100.0, 6)
    if pct == int(pct) and 0 < pct < 100:
        return 'K' + words_under_100(int(pct))
    return 'K' + spell_digits(repr(float(kappa)))


def check_macro_name(name):
    if not MACRO_RE.match(name):
        raise ValueError(f'invalid macro name {name!r}: need num + capital + letters only')
    return name


class Macros:
    """Ordered registry of macros with a meaning and a source path for each."""

    def __init__(self):
        self.items = {}

    def add(self, name, value, meaning, source):
        check_macro_name(name)
        if name in self.items:
            raise ValueError(f'duplicate macro {name}')
        self.items[name] = (str(value), meaning, source)

    def render(self):
        lines = [HEADER, '%', '% Macros (name: meaning [source JSON path])']
        for name, (_, meaning, source) in self.items.items():
            lines.append(f'%   \\{name}: {meaning} [{source}]')
        lines.append('')
        for name, (value, _, _) in self.items.items():
            lines.append(f'\\newcommand{{\\{name}}}{{{tex(value)}}}')
        return '\n'.join(lines) + '\n'


